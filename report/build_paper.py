def parse_content(path: Path):
    text = path.read_text(encoding="utf-8")
    _, fm, body = text.split("---", 2)
    meta, key = {}, None
    for line in fm.strip().splitlines():
        m = re.match(r"^(\w+):\s?(.*)$", line)
        if m:
            key = m.group(1)
            meta[key] = m.group(2).strip()
        elif key:
            meta[key] += "\n" + line.strip() if key == "footnote" else " " + line.strip()
    blocks, buf = [], []
    for line in body.splitlines():
        if not line.strip():
            if buf:
                blocks.append(" ".join(buf))
                buf = []
            continue
        if line.startswith(("#", "$$", "![", "{{")):
            if buf:
                blocks.append(" ".join(buf))
                buf = []
            blocks.append(line.strip())
        else:
            buf.append(line.strip())
    if buf:
        blocks.append(" ".join(buf))
    return meta, blocks


def build(lang: str) -> Path:
    meta, blocks = parse_content(OUT_DIR / f"content_{lang}.md")
    bib = json.loads((OUT_DIR / "references.json").read_text(encoding="utf-8"))
    bib = {k: (v[lang] if isinstance(v, dict) and lang in v else v.get("ieee", v)
               if isinstance(v, dict) else v) for k, v in bib.items()}
    paper = Paper(lang, meta)
    # first pass: number figures / tables / equations in order of definition
    nfig = ntab = neq = 0
    for b in blocks:
        if b.startswith("!["):
            nfig += 1
            lab = re.search(r"\{#(fig:[\w-]+)\}", b)
            if lab:
                paper.labels[lab.group(1)] = str(nfig)
        elif b.startswith("{{"):
            ntab += 1
            lab = re.search(r"\{#(tab:[\w-]+)\}", b)
            if lab:
                paper.labels[lab.group(1)] = ROMAN[ntab - 1]
        elif b.startswith("$$"):
            neq += 1
            lab = re.search(r"\{#(eq:[\w-]+)\}", b)
            if lab:
                paper.labels[lab.group(1)] = str(neq)
    paper.front_matter()
    counters = {"h1": 0, "h2": 0}
    nfig = ntab = neq = 0
    for b in blocks:
        if b.startswith("#"):
            level = len(b) - len(b.lstrip("#"))
            title = b.lstrip("#").strip()
            numbered = not title.endswith("{-}")
            title = title.replace("{-}", "").strip()
            if title.lower() in ("references", "kaynaklar"):
                paper.references(bib, title)
                continue
            paper.heading(level, title, numbered, counters)
        elif b.startswith("$$"):
            neq += 1
            latex = re.match(r"\$\$(.*?)\$\$", b).group(1).strip()
            paper.equation(latex, neq)
        elif b.startswith("!["):
            nfig += 1
            m = re.match(r"!\[(\w+)\]\(([^)]+)\)(?:\{#[\w:-]+\})?\s*(.*)$", b)
            span, fname, caption = m.group(1), m.group(2), m.group(3)
            paper.figure(span, FIG_DIR / lang / fname, nfig, caption)
        elif b.startswith("{{"):
            ntab += 1
            m = re.match(r"\{\{table:(\w+)\|(\w+)\}\}", b)
            paper.table(m.group(1), m.group(2), ntab)
        else:
            paper.paragraph(b)
    if meta.get("bio"):
        name, _, text = meta["bio"].partition("|")
        paper.bio(name.strip(), text.strip())
    out = OUT_DIR / ("Esenboga_LowVisibility_Nowcasting_IEEE_EN.docx" if lang == "en"
                     else "Esenboga_DusukGorus_Tahmini_IEEE_TR.docx")
    paper.save(out)
    unused = set(bib) - set(paper.cite_order)
    print(f"{lang}: {out.name} | {len(paper.cite_order)} references cited, "
          f"{nfig} figures, {ntab} tables, {neq} equations; uncited: {sorted(unused)}")
    return out


def to_pdf(docx_path: Path) -> Path:
    pdf = docx_path.with_suffix(".pdf")
    ps = (f"$w = New-Object -ComObject Word.Application; $w.Visible = $false; "
          f"$d = $w.Documents.Open('{docx_path}'); $d.Fields.Update() | Out-Null; "
          f"$d.SaveAs([ref] '{pdf}', [ref] 17); $d.Close([ref] 0); $w.Quit()")
    subprocess.run(["powershell", "-NoProfile", "-Command", ps], check=True, timeout=300)
    return pdf


def render_pages(pdf: Path, out_dir: Path, zoom: float = 1.6) -> list[Path]:
    import fitz

    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    with fitz.open(pdf) as d:
        for i, page in enumerate(d):
            pth = out_dir / f"{pdf.stem}_p{i + 1:02d}.png"
            page.get_pixmap(matrix=fitz.Matrix(zoom, zoom)).save(pth)
            paths.append(pth)
    return paths


