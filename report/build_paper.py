def tr_upper(s: str, lang: str) -> str:
    if lang == "tr":
        s = s.replace("i", "İ").replace("ı", "I")
    return s.upper()


def set_run_fmt(run, bold=None, italic=None, size=None, small_caps=None, vert=None, font=None):
    if bold is not None:
        run.bold = bold
    if italic is not None:
        run.italic = italic
    if size is not None:
        run.font.size = Pt(size)
    if small_caps is not None:
        run.font.small_caps = small_caps
    if vert == "sub":
        run.font.subscript = True
    elif vert == "sup":
        run.font.superscript = True
    if font:
        run.font.name = font


def copy_ppr(par, proto_el):
    """Replace paragraph properties of ``par`` by a copy of the prototype's pPr."""
    ppr = proto_el.find(qn("w:pPr"))
    old = par._p.find(qn("w:pPr"))
    if old is not None:
        par._p.remove(old)
    if ppr is not None:
        new = copy.deepcopy(ppr)
        for sp in new.findall(qn("w:sectPr")):
            new.remove(sp)
        par._p.insert(0, new)


MATH_NS = "http://schemas.openxmlformats.org/officeDocument/2006/math"


def _fix_nary(root: etree._Element) -> None:
    """MML2OMML leaves the operand of a sum outside the n-ary object (rendered as a large gap).
    Move the following siblings into the empty <m:e> until a separator (',', '=', ';')."""
    m = "{%s}" % MATH_NS
    for nary in list(root.iter(m + "nary")):
        e = nary.find(m + "e")
        if e is None or len(e):
            continue
        parent = nary.getparent()
        sib = nary.getnext()
        while sib is not None:
            txt = "".join(sib.itertext()).strip() if sib.tag == m + "r" else ""
            if txt in (",", "=", ";", ", ") or txt.startswith(","):
                break
            nxt = sib.getnext()
            parent.remove(sib)
            e.append(sib)
            sib = nxt


def omml_from_latex(latex: str, xslt) -> etree._Element | None:
    try:
        mml = latex_to_mathml(latex)
        res = xslt(etree.fromstring(mml.encode("utf-8")))
        root = res.getroot()
        _fix_nary(root)
        return root
    except Exception as exc:  # fall back to plain text when conversion fails
        print("equation conversion failed:", latex, exc)
        return None


def png_width_in(path: Path, dpi: float = 400.0) -> float:
    from PIL import Image

    with Image.open(path) as im:
        return im.size[0] / dpi


_TR_WORDS = {1: "bir", 2: "iki", 3: "üç", 4: "dört", 5: "beş", 6: "altı", 7: "yedi", 8: "sekiz",
             9: "dokuz", 10: "on", 20: "yirmi", 30: "otuz", 40: "kırk", 50: "elli", 60: "altmış",
             70: "yetmiş", 80: "seksen", 90: "doksan"}
_ROMAN = {"I": 1, "V": 5, "X": 10, "L": 50, "C": 100}


def _tr_last_word(n: int) -> str:
    """Last word of the Turkish reading of n (it determines the suffix harmony)."""
    if n == 0:
        return "sıfır"
    if n % 10:
        return _TR_WORDS[n % 10]
    if n % 100:
        return _TR_WORDS[n % 100]
    return "yüz" if n % 1000 else "bin"


def _roman_value(r: str) -> int:
    total = 0
    for a, b in zip(r, r[1:] + " "):
        v = _ROMAN[a]
        total += -v if b != " " and _ROMAN.get(b, 0) > v else v
    return total


def harmonize_tr(text: str) -> str:
    """Turkish locative/ablative suffixes after numbers: Tablo III'de -> Tablo III'te, Şekil 3'deki -> 3'teki."""
    def fix(m):
        num, suffix, tail = m.group(1), m.group(2), m.group(3) or ""
        n = _roman_value(num) if num.isalpha() else int(num)
        word = _tr_last_word(n)
        vowel = [c for c in word if c in "aeıioöuü"][-1]
        cons = "t" if word[-1] in "çfhkpsşt" else "d"
        vow = "e" if vowel in "eiöü" else "a"
        return f"{num}'{cons}{vow}{'n' if suffix.endswith('n') else ''}{tail}"
    return re.sub(r"\b(\d+|[IVXLC]+)'([dt][ea]n?)(ki)?\b", fix, text)


def localize_tr(text: str) -> str:
    """Turkish number style: decimal comma, '%' before the number, ';' inside intervals."""
    text = re.sub(r"\[(-?\d+\.\d+), (-?\d+\.\d+)\]", r"[\1; \2]", text)
    text = re.sub(r"(?<=\d)\.(?=\d)", ",", text)
    return re.sub(r"(\d+(?:,\d+)?)%", r"%\1", text)


# ============================================================================ document
class Paper:
    def __init__(self, lang: str, meta: dict):
        self.lang = lang
        self.meta = meta
        self.doc = docx.Document(TEMPLATE)
        body = self.doc.element.body
        kids = list(body.iterchildren())
        self.proto = {name: copy.deepcopy(kids[i]) for name, i in (
            ("title", 0), ("authors", 2), ("abstract", 6), ("index", 8), ("h1", 10),
            ("dropcap", 11), ("first", 12), ("body", 13), ("h2", 35), ("tab_no", 39),
            ("tab_title", 40), ("equation", 46), ("ref_head", 125), ("ref", 133),
            ("bio", 226))}
        self.sec_break = kids[4]            # end of single-column title section
        self.foot_par = kids[5]             # paragraph holding the first-page footnote mark
        self.final_sect = body.find(qn("w:sectPr"))
        for el in kids:
            if el is not self.sec_break and el is not self.foot_par and el is not self.final_sect:
                body.remove(el)
        pg = self.final_sect.find(qn("w:pgNumType"))
        if pg is not None:                  # only the first section starts numbering at 1
            self.final_sect.remove(pg)
        self.xslt = etree.XSLT(etree.parse(str(MML2OMML))) if MML2OMML.exists() else None
        self.cite_order: list[str] = []
        self.labels: dict[str, str] = {}
        self.first_body_par = True
        if lang == "tr":
            self._set_language("tr-TR")

    # ------------------------------------------------------------------ setup
    def _set_language(self, code: str) -> None:
        styles = self.doc.styles.element
        for lang_el in styles.iter(qn("w:lang")):
            lang_el.set(qn("w:val"), code)

    def front_matter(self) -> None:
        m = self.meta
        # title and authors go before the section break of the single-column section
        tp = self._new_par_before(self.sec_break, self.proto["title"])
        tp.add_run(m["title"])
        blank = self._new_par_before(self.sec_break, self.proto["authors"])
        ap = self._new_par_before(self.sec_break, self.proto["authors"])
        r = ap.add_run(m["authors"])
        set_run_fmt(r, size=11)
        del blank
        # abstract & index terms (two-column section, after the footnote paragraph)
        p = self.doc.add_paragraph()
        copy_ppr(p, self.proto["abstract"])
        set_run_fmt(p.add_run("Abstract" if self.lang == "en" else "Özet"), bold=True, italic=True, size=9)
        set_run_fmt(p.add_run("—"), bold=True, size=9)
        self.inline(p, m["abstract"], size=9, bold=True)
        self.doc.add_paragraph()
        p = self.doc.add_paragraph()
        copy_ppr(p, self.proto["index"])
        set_run_fmt(p.add_run("Index Terms" if self.lang == "en" else "Anahtar Kelimeler"),
                    bold=True, italic=True, size=9)
        set_run_fmt(p.add_run("—" + m["keywords"]), bold=True, size=9)
        self._footnote(m["footnote"])
        self._header(m["header"])

    def _new_par_before(self, anchor, proto):
        new_p = OxmlElement("w:p")
        anchor.addprevious(new_p)
        par = docx.text.paragraph.Paragraph(new_p, self.doc._body)
        copy_ppr(par, proto)
        return par

    def _footnote(self, text: str) -> None:
        for part in self.doc.part.package.parts:
            if str(part.partname) == "/word/footnotes.xml":
                root = etree.fromstring(part.blob)
                ns = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main"}
                for fn in root.findall("w:footnote", ns):
                    fid = fn.get(qn("w:id"))
                    if fid == "2":
                        root.remove(fn)
                    elif fid == "1":
                        for p in fn.findall("w:p", ns):
                            fn.remove(p)
                        for para in text.split("\n"):
                            p = etree.SubElement(fn, qn("w:p"))
                            ppr = etree.SubElement(p, qn("w:pPr"))
                            st = etree.SubElement(ppr, qn("w:pStyle"))
                            st.set(qn("w:val"), "FootnoteText")
                            r = etree.SubElement(p, qn("w:r"))
                            t = etree.SubElement(r, qn("w:t"))
                            t.text = para
                            t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
                part._blob = etree.tostring(root, xml_declaration=True, encoding="UTF-8",
                                            standalone=True)

    def _header(self, text: str) -> None:
        hdr = self.doc.sections[0].header
        for p in hdr.paragraphs:
            for r in p.runs:
                if "REPLACE" in r.text or "MANUSCRIPT" in r.text or "DOUBLE" in r.text:
                    r.text = ""
            if not any(r.text for r in p.runs if r.text.strip()):
                continue
        # running head before the PAGE field of the (right-aligned) header paragraph
        first = hdr.paragraphs[0]
        for p in hdr.paragraphs:
            if "PAGE" in p._p.xml:
                first = p
        for r in first.runs:
            if r.text.strip() in (">", "<", "3>", "> ", " <"):
                r.text = ""
        run = first.add_run(text + "   ")
        set_run_fmt(run, size=8)
        ppr = first._p.find(qn("w:pPr"))
        anchor = ppr if ppr is not None else None
        if anchor is not None:
            anchor.addnext(run._r)
        else:
            first._p.insert(0, run._r)

    # ------------------------------------------------------------------ inline text
    def inline(self, par, text: str, size=None, bold=None, italic_all=False):
        """Render inline markup (citations, refs, italic/bold, inline math)."""
        text = self._resolve(text)
        tokens = re.split(r"(\*\*[^*]+\*\*|\*[^*]+\*|\$[^$]+\$)", text)
        for tok in tokens:
            if not tok:
                continue
            if tok.startswith("**"):
                set_run_fmt(par.add_run(tok[2:-2]), bold=True, size=size)
            elif tok.startswith("*"):
                set_run_fmt(par.add_run(tok[1:-1]), italic=True, size=size, bold=bold)
            elif tok.startswith("$"):
                self._inline_math(par, tok[1:-1], size, bold)
            else:
                set_run_fmt(par.add_run(tok), size=size, bold=bold, italic=italic_all or None)

    def _inline_math(self, par, s: str, size, bold):
        s = s.replace(r"\,", "\u2009").replace(r"\;", " ").replace(r"\ ", " ")
        s = s.replace(r"\{", "⦃").replace(r"\}", "⦄")
        s = re.sub(r"\\mathbf\{([^}]*)\}", r"⟦\1⟧", s)        # bold upright marker
        for k, v in sorted(GREEK.items(), key=lambda kv: -len(kv[0])):
            s = s.replace(k, v)
        s = re.sub(r"\\mathrm\{([^}]*)\}", r"⟨\1⟩", s)        # upright text marker
        s = re.sub(r"\\text\{([^}]*)\}", r"⟨\1⟩", s)
        s = re.sub(r"(?<=[\w)⟩\s])-(?=[\w(⟨\s])", "−", s)    # true minus sign
        i = 0
        while i < len(s):
            ch = s[i]
            if ch in "_^" and i + 1 < len(s):
                vert = "sub" if ch == "_" else "sup"
                if s[i + 1] == "{":
                    j = s.index("}", i + 1)
                    content = s[i + 2:j]
                    i = j + 1
                else:
                    content = s[i + 1]
                    i += 2
                upright = content.startswith("⟨")
                content = content.strip("⟨⟩")
                set_run_fmt(par.add_run(content), italic=not upright and content.isalpha(),
                            size=size, bold=bold, vert=vert)
                continue
            if ch == "⟨":
                j = s.index("⟩", i)
                set_run_fmt(par.add_run(s[i + 1:j]), size=size, bold=bold)
                i = j + 1
                continue
            if ch == "⟦":
                j = s.index("⟧", i)
                set_run_fmt(par.add_run(s[i + 1:j]), size=size, bold=True)
                i = j + 1
                continue
            j = i
            if ch.isalpha():
                while j < len(s) and s[j].isalpha():
                    j += 1
                set_run_fmt(par.add_run(s[i:j]), italic=True, size=size, bold=bold)
            else:
                while j < len(s) and not s[j].isalpha() and s[j] not in "_^⟨⟦":
                    j += 1
                chunk = s[i:j].replace("{", "").replace("}", "").replace("⦃", "{").replace("⦄", "}")
                set_run_fmt(par.add_run(chunk), size=size, bold=bold)
            i = j

    def _resolve(self, text: str) -> str:
        def cite(m):
            keys = [k.strip().lstrip("@") for k in m.group(1).split(";")]
            nums = []
            for k in keys:
                if k not in self.cite_order:
                    self.cite_order.append(k)
                nums.append(self.cite_order.index(k) + 1)
            nums.sort()
            # IEEE: consecutive runs of 3+ are shown as ranges [3]-[5]
            parts, run = [], [nums[0]]
            for n in nums[1:]:
                if n == run[-1] + 1:
                    run.append(n)
                else:
                    parts.append(run)
                    run = [n]
            parts.append(run)
            out = []
            for r in parts:
                if len(r) >= 3:
                    out.append(f"[{r[0]}]–[{r[-1]}]")
                else:
                    out.extend(f"[{n}]" for n in r)
            return ", ".join(out)

        text = re.sub(r"\[(@[^\]]+)\]", cite, text)
        text = re.sub(r"@((?:fig|tab|eq):[\w-]+)",
                      lambda m: self.labels.get(m.group(1), "??"), text)
        if self.lang == "tr":
            text = harmonize_tr(text)
        return text

    # ------------------------------------------------------------------ blocks
    def heading(self, level: int, text: str, numbered: bool, counters: dict):
        if level == 1:
            p = self.doc.add_paragraph()
            copy_ppr(p, self.proto["h1"])
            if numbered:
                counters["h1"] += 1
                counters["h2"] = 0
                p.add_run(f"{ROMAN[counters['h1'] - 1]}. ")
            p.add_run(text)
        else:
            p = self.doc.add_paragraph()
            copy_ppr(p, self.proto["h2"])
            counters["h2"] += 1
            p.add_run(f"{chr(64 + counters['h2'])}. ")
            self.inline(p, text)

    def paragraph(self, text: str):
        if self.first_body_par:
            self.first_body_par = False
            m = re.match(r"(\w)(\w*)(.*)", text, re.S)
            if m:
                dc = self.doc.add_paragraph()
                copy_ppr(dc, self.proto["dropcap"])
                r = dc.add_run(tr_upper(m.group(1), self.lang))
                rpr_src = self.proto["dropcap"].find(qn("w:r")).find(qn("w:rPr"))
                r._r.insert(0, copy.deepcopy(rpr_src))
                p = self.doc.add_paragraph()
                copy_ppr(p, self.proto["first"])
                set_run_fmt(p.add_run(tr_upper(m.group(2), self.lang)), small_caps=True)
                self.inline(p, m.group(3))
                return
        p = self.doc.add_paragraph(style="Text")
        self.inline(p, text)

    def equation(self, latex: str, number: int):
        p = self.doc.add_paragraph()
        copy_ppr(p, self.proto["equation"])
        p.add_run().add_tab()
        om = omml_from_latex(latex, self.xslt) if self.xslt is not None else None
        if om is not None:
            p._p.append(om)
        else:
            self._inline_math(p, latex, None, None)
        r = p.add_run()
        r.add_tab()
        p.add_run(f"({number})")

    def section_break(self, columns: int):
        """Insert a continuous section break; the *ending* section gets ``columns``."""
        p = self.doc.add_paragraph()
        ppr = p._p.get_or_add_pPr()
        sect = copy.deepcopy(self.final_sect)
        for el in list(sect):
            if el.tag in (qn("w:headerReference"), qn("w:footerReference"), qn("w:pgNumType")):
                sect.remove(el)
        cols = sect.find(qn("w:cols"))
        new_cols = OxmlElement("w:cols")
        if columns == 1:
            new_cols.set(qn("w:space"), "288")
        else:
            new_cols.set(qn("w:num"), "2")
            new_cols.set(qn("w:space"), "288")
        sect.replace(cols, new_cols)
        typ = sect.find(qn("w:type"))
        if typ is None:
            typ = OxmlElement("w:type")
            sect.insert(0, typ)
        typ.set(qn("w:val"), "continuous")
        ppr.append(sect)
        fmt = p.paragraph_format
        fmt.space_before = Pt(0)
        fmt.space_after = Pt(0)
        r = p.add_run()
        r.font.size = Pt(1)

    def figure(self, span: str, path: Path, number: int, caption: str):
        if span == "page":
            self.section_break(2)
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(6)
        p.paragraph_format.keep_with_next = True
        width = min(png_width_in(path), 7.0 if span == "page" else 3.45)
        p.add_run().add_picture(str(path), width=Inches(width))
        c = self.doc.add_paragraph(style="Figure Caption")
        c.paragraph_format.space_after = Pt(8)
        set_run_fmt(c.add_run(f"Fig. {number}. " if self.lang == "en" else f"Şekil {number}. "), size=8)
        self.inline(c, caption, size=8)
        if span == "page":
            self.section_break(1)

    def table(self, key: str, span: str, number: int):
        spec = T.build(key, self.lang)
        if span == "page":
            self.section_break(2)
        p = self.doc.add_paragraph()
        copy_ppr(p, self.proto["tab_no"])
        p.paragraph_format.keep_with_next = True
        set_run_fmt(p.add_run(f"TABLE {ROMAN[number - 1]}" if self.lang == "en"
                              else f"TABLO {ROMAN[number - 1]}"), size=8)
        p = self.doc.add_paragraph(style="Table Title")
        p.paragraph_format.keep_with_next = True
        p.paragraph_format.space_after = Pt(3)
        self.inline(p, spec["title"], size=8)
        total = 7.0 if span == "page" else 3.45
        widths = spec.get("widths") or [1] * len(spec["header"][0])
        widths = [w / sum(widths) * total for w in widths]
        rows = spec["header"] + spec["rows"]
        tbl = self.doc.add_table(rows=len(rows), cols=len(widths))
        tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
        tbl.autofit = False
        self._table_borders(tbl, len(spec["header"]), spec.get("rules", []))
        for i, row in enumerate(rows):
            for j, val in enumerate(row):
                cell = tbl.cell(i, j)
                cell.width = Inches(widths[j])
                cp = cell.paragraphs[0]
                cp.paragraph_format.space_before = Pt(0.5)
                cp.paragraph_format.space_after = Pt(0.5)
                cp.alignment = (WD_ALIGN_PARAGRAPH.LEFT if j < spec.get("left_cols", 1)
                                else WD_ALIGN_PARAGRAPH.CENTER)
                text = str(val)
                bold = text.startswith("**") and text.endswith("**")
                if bold:
                    text = text[2:-2]
                fsize = 7 if span == "col" else 7.5
                if self.lang == "tr":
                    text = localize_tr(text)
                # the paragraph mark sets the line height of empty cells: match the table font
                rpr = OxmlElement("w:rPr")
                sz = OxmlElement("w:sz")
                sz.set(qn("w:val"), str(int(fsize * 2)))
                rpr.append(sz)
                cp._p.get_or_add_pPr().append(rpr)
                if text:
                    self.inline(cp, text, size=fsize,
                                bold=True if (bold or i < len(spec["header"])) else None)
        for j, w in enumerate(widths):
            for cell in tbl.columns[j].cells:
                cell.width = Inches(w)
        if spec.get("notes"):
            n = self.doc.add_paragraph(style="Figure Caption")
            n.paragraph_format.space_before = Pt(2)
            self.inline(n, localize_tr(spec["notes"]) if self.lang == "tr" else spec["notes"], size=7)
        sp = self.doc.add_paragraph()
        sp.paragraph_format.space_after = Pt(4)
        if span == "page":
            self.section_break(1)

    @staticmethod
    def _table_borders(tbl, n_header: int, rules: list[int]):
        tblPr = tbl._tbl.tblPr
        borders = OxmlElement("w:tblBorders")
        for edge, sz in (("top", "8"), ("bottom", "8")):
            el = OxmlElement(f"w:{edge}")
